create or replace function public.generate_membership_register_keys(
  p_academic_year_id uuid,
  p_count integer,
  p_secret text,
  p_created_by_user_id uuid
)
returns setof public.membership_register_keys
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_academic_year public.academic_years%rowtype;
  v_start_sequence integer;
  v_sequence integer;
  v_register_key text;
  v_digest text;
  v_row public.membership_register_keys%rowtype;
begin
  if p_count < 1 or p_count > 100 then
    raise exception 'INVALID_COUNT';
  end if;

  if p_secret is null or length(trim(p_secret)) < 16 then
    raise exception 'REGISTER_KEY_SECRET_NOT_CONFIGURED';
  end if;

  select * into v_academic_year
  from public.academic_years
  where id = p_academic_year_id;

  if not found then
    raise exception 'ACADEMIC_YEAR_NOT_FOUND';
  end if;

  perform pg_advisory_xact_lock(
    hashtext('membership_register_keys:' || p_academic_year_id::text)
  );

  select coalesce(max(sequence_number), 0) + 1 into v_start_sequence
  from public.membership_register_keys
  where academic_year_id = p_academic_year_id;

  for v_sequence in v_start_sequence..(v_start_sequence + p_count - 1) loop
    v_digest := upper(
      substring(
        encode(
          hmac(
            v_academic_year.year || 'NTUSTBGC' || lpad(v_sequence::text, 3, '0'),
            p_secret,
            'sha256'::text
          ),
          'hex'
        ) from 1 for 8
      )
    );
    v_register_key := v_academic_year.year || 'NTUSTBGC'
      || lpad(v_sequence::text, 3, '0') || v_digest;

    insert into public.membership_register_keys (
      academic_year_id,
      sequence_number,
      register_key,
      status,
      created_by_user_id
    ) values (
      p_academic_year_id,
      v_sequence,
      v_register_key,
      'available',
      p_created_by_user_id
    ) returning * into v_row;

    return next v_row;
  end loop;
end;
$$;

